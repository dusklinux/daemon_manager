    // Store explicit choices separately so future builtin changes can take effect.
    @Published var customDefaults: [String: Bool] {
        didSet { UserDefaults.standard.set(customDefaults, forKey: "userConfiguredOverrides") }
    }

    init() {
        let defaults = UserDefaults.standard
        if let saved = defaults.dictionary(forKey: "userConfiguredOverrides") as? [String: Bool] {
            customDefaults = saved
        } else if let legacy = defaults.dictionary(forKey: "userConfiguredDefaults") as? [String: Bool] {
            // The old format copied every builtin value. Retain differing choices.
            let changed: Set<String> = ["com.apple.searchd", "com.apple.biomed", "com.apple.syncdefaultsd",
                                        "com.apple.imagent", "com.apple.identityservicesd", "com.apple.nehelper",
                                        "com.apple.nehelper-embedded", "com.apple.mobile.lockdown", "com.apple.absd",
                                        "com.apple.cdpd", "com.apple.followupd", "com.apple.photos.ImageConversionService", "com.apple.photos.VideoConversionService", "com.apple.passd", "com.apple.SecureBackupDaemon", "com.apple.contextstored"]
            let previousBuiltin: [String: Bool] = [
                "com.apple.ShortcutsUI": false, "com.apple.siriactionsd": false,
                "com.apple.WebBookmarks.webbookmarksd": true, "com.apple.Safari.History": true,
                "com.apple.imcore.imtransferagent": true, "com.apple.ids.IDSCredentialsAgent": true,
                "com.apple.idsfoundation.IDSRemoteURLConnectionAgent": true
            ]
            customDefaults = legacy.filter { label, value in
                // PosterBoard previously inherited On; its revised default is Off.
                let oldBuiltin = previousBuiltin[label] ?? (label == "com.apple.PosterBoard" ? false : changed.contains(label) ? true : Self.builtinDefaults[label])
                return oldBuiltin != value
            }
        } else {
            customDefaults = [:]
        }
        defaults.set(customDefaults, forKey: "userConfiguredOverrides")
    }

    func targetState(for label: String) -> Bool {
        customDefaults[label] ?? Self.builtinDefaults[label] ?? false
    }

    func setTargetState(for label: String, disable: Bool) {
        customDefaults[label] = disable
    }

    func resetToBuiltin() {
        customDefaults = [:]
    }
